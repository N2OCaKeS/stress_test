"""Общие числовые пределы для query-параметров read-API."""

# Десять миллионов — потолок для `offset` в пагинации списочных эндпоинтов.
# PostgreSQL гоняет постраничный прoскролл до этого оффсета даже когда
# подходящих строк нет; на больших значениях statement_timeout начинает
# рвать запросы. Реалистичный потолок журнала на годы вперёд.
MAX_QUERY_OFFSET = 10_000_000

# Default-cap верхнего предела `limit` для query-эндпоинтов аудита.
MAX_QUERY_LIMIT = 1000

# Жёсткий потолок числа строк в одном CSV-экспорте `GET /events/export`.
# Экспорт читает весь page разом (под server-side cursor), поэтому он не
# может тянуть журнал целиком — иначе один запрос за широкое окно вытащил
# бы миллионы строк и съел память пода. 50k строк ≈ десяток мегабайт CSV —
# покрывает «экспорт за сутки» с запасом; за пределами cap ответ помечается
# заголовком `X-Export-Truncated: true`, и оператор сужает окно/фильтр.
MAX_EXPORT_ROWS = 50_000
