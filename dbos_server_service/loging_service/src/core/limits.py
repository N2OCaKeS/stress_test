"""Общие числовые пределы для query-параметров read-API."""

# Десять миллионов — потолок для `offset` в пагинации списочных эндпоинтов.
# PostgreSQL гоняет постраничный прoскролл до этого оффсета даже когда
# подходящих строк нет; на больших значениях statement_timeout начинает
# рвать запросы. Реалистичный потолок журнала на годы вперёд.
MAX_QUERY_OFFSET = 10_000_000

# Default-cap верхнего предела `limit` для query-эндпоинтов аудита.
MAX_QUERY_LIMIT = 1000
