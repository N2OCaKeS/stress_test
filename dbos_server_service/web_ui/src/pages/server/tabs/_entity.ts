import type { Server } from "@/api/server/types";
import type { Vm } from "@/api/server/vms";

/**
 * Ссылка на сущность, для которой рендерится вкладка. Карточка сервера и
 * карточка ВМ используют одни и те же файлы-компоненты вкладок из `./tabs/`;
 * различаются только источник данных и набор доступных операций. Дискриминатор —
 * поле `kind`.
 *
 * Вариант `server` намеренно несёт только сам объект: серверные вкладки, как и
 * раньше, берут capability из persona и ходят в server-эндпоинты. Вариант `vm`
 * тащит контекст страницы ВМ (mock-режим, право управления, колбэк обновления
 * списка) — у ВМ нет persona-матрицы прав на каждую операцию, право приходит
 * сверху одним флагом.
 */
export type EntityRef =
  | { kind: "server"; server: Server }
  | {
      kind: "vm";
      vm: Vm;
      /** mock-режим страницы ВМ: операции не уходят на backend. */
      mock: boolean;
      /** есть ли у пользователя право на управляющие операции над ВМ. */
      canManage: boolean;
      /** дёрнуть после мутации — родитель перечитает список/карточку ВМ. */
      onChanged: () => void;
    };

/**
 * Общий проп-контракт вкладки, рендерящейся и для сервера, и для ВМ.
 *
 * `entity` необязателен: если его нет, вкладка работает в прежнем «серверном»
 * режиме по `server`/`serverId` (обратная совместимость со старыми вызовами и
 * тестами). Диспетчеры передают `entity` явно.
 */
export interface EntityTabProps {
  entity?: EntityRef;
  /** Локальное обновление карточки после мутации (PATCH и т.п.). */
  onEntityUpdated?: (next: Server | Vm) => void;
}
